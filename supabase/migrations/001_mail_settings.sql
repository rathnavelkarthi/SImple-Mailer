-- Mail Settings Table
-- Stores Gmail credentials that can be updated after login

create table if not exists public.mail_settings (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null,

  -- Gmail configuration
  gmail_user text,
  gmail_app_password text,
  gmail_enabled boolean default false
);

-- Set default row if table is empty
insert into public.mail_settings (id, gmail_enabled)
select 1, false
where not exists (select 1 from public.mail_settings);

---- Permissions ----
alter table public.mail_settings enable row level security;

-- Only allow service role to manage settings (admin access)
alter table public.mail_settings
  remove constraint all,
  add constraint on_service_role_only check (auth.jwt()->>'role' = 'service_role');

grant select, insert, update, delete on public.mail_settings to service_role;
grant usage on sequence public.mail_settings_id_seq to service_role;
